function pageSummaryItem(assignment, type) {
  if (!assignment.page) return `no ${type} pages listed`;
  const label = type === "wordlist" ? "wordlist" : type;
  const plural = assignment.total === 1 ? "page" : "pages";
  return `${assignment.index} of ${assignment.total} ${assignment.level} ${label} ${plural}`;
}

function pagePositionLabel(assignment, type) {
  if (!assignment.page) return "No page listed yet";
  const label = type === "wordlist" ? "wordlist" : type;
  const plural = assignment.total === 1 ? "page" : "pages";
  return `Page ${assignment.index} of ${assignment.total} ${assignment.level} ${label} ${plural}`;
}

function formatPage(assignment) {
  return assignment.page ? `Reader ${assignment.reader}, p. ${assignment.page}` : "Use teacher page";
}

function pageAssignment(group, skill, type, offset = 0, level = group.readerLevel || "AB") {
  const pages = pageList(skill, type, level);
  if (!pages.length) return { reader: skill.reader, page: null, level, index: 0, total: 0, position: "not available" };
  const baseIndex = group.pageProgress?.[type] || 0;
  const index = Math.min(baseIndex + offset, pages.length - 1);
  return {
    reader: skill.reader,
    page: pages[index],
    level: resolvedLevel(skill, type, level),
    index: index + 1,
    total: pages.length,
    position: `${index + 1} of ${pages.length}`
  };
}

function pageList(skill, type, level) {
  const pages = skill.pages?.[type] || {};
  const listed = pages[level]?.length ? pages[level] : pages.AB || pages.A || pages.B || [];
  if (type !== "wordlist") return listed;
  const resolved = pages[level]?.length ? level : pages.AB?.length ? "AB" : pages.A?.length ? "A" : pages.B?.length ? "B" : level;
  const fullPages = listed.filter((page) => chartingPageEntry(skill.id, resolved, page).count >= 30);
  if (fullPages.length) return fullPages;
  return listed.filter((page) => chartingPageEntry(skill.id, resolved, page).count >= 15);
}

function resolvedLevel(skill, type, preferred) {
  const pages = skill.pages?.[type] || {};
  if (pages[preferred]?.length) return preferred;
  if (pages.AB?.length) return "AB";
  if (pages.A?.length) return "A";
  if (pages.B?.length) return "B";
  return preferred;
}

function levelSuggestion(group) {
  const recent = group.chartResults.slice(-2);
  if (recent.length >= 2 && recent.every((result) => result.automaticity && result.fluency)) {
    return "Two strong checks in a row: B may be appropriate if the group needs more challenge.";
  }
  if (recent.length && recent.at(-1).correct < 12) {
    return "Most recent check missed accuracy: consider A or repeat the same AB page.";
  }
  return "Use AB unless results show the page is too hard or too easy.";
}

