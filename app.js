function selectActiveStudent(student, options = {}) {
  const group = activeGroup();
  if (!student || !group.students.includes(student)) return;
  if (student === group.activeStudent) {
    syncActiveStudentUi(group);
    return;
  }

  if (options.sourceCard) {
    saveLiveRecordIfNeeded(options.sourceCard);
  } else {
    saveDirtyLiveCards();
  }

  group.activeStudent = student;
  saveState();
  syncActiveStudentUi(group);

  if (options.resetSource && options.sourceCard) {
    resetLiveCharting(options.sourceCard);
  }
}

