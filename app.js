function knownVowels(substep) {
  if (isAtLeastSubstep(substep, "5.5")) {
    return "short vowels: ă, ĕ, ĭ, ŏ, ŭ; v-e long sounds: ā-e, ē-e, ī-e, ō-e, ū-e; open syllable long vowels: ā, ē, ī, ō, ū; final y: ē, ī; open-syllable exceptions: schwa/short i as taught";
  }
  if (isAtLeastSubstep(substep, "5.1")) {
    return "short vowels: ă, ĕ, ĭ, ŏ, ŭ; v-e long sounds: ā-e, ē-e, ī-e, ō-e, ū-e; open syllable long vowels: ā, ē, ī, ō, ū; y as vowel";
  }
  if (isAtLeastSubstep(substep, "4.1")) {
    return "short vowels: ă, ĕ, ĭ, ŏ, ŭ; v-e long sounds: ā-e, ē-e, ī-e, ō-e, ū-e";
  }
  if (isAtLeastSubstep(substep, "1.2")) {
    return "short vowels: ă, ĕ, ĭ, ŏ, ŭ";
  }
  return "short vowels: ă, ĭ, ŏ";
}

function knownConsonants(substep) {
  const base = isAtLeastSubstep(substep, "1.2") ? knownConsonantSets["1.2"] : knownConsonantSets["1.1"];
  const additions = [];
  if (isAtLeastSubstep(substep, "7.1")) additions.push("c=/s/ before e, i, y", "g=/j/ before e, i, y");
  if (isAtLeastSubstep(substep, "7.2")) additions.push("ce", "ge", "dge");
  if (isAtLeastSubstep(substep, "7.3")) additions.push("ph", "tch");
  return [base].concat(additions).join(", ");
}

function listKnown(entries, substep) {
  const values = entries.filter(([introduced]) => isAtLeastSubstep(substep, introduced)).map(([, value]) => value);
  return values.length ? values.join(", ") : "n/a";
}

function isAtLeastSubstep(current, target) {
  const [currentStep, currentSubstep] = current.split(".").map(Number);
  const [targetStep, targetSubstep] = target.split(".").map(Number);
  return currentStep > targetStep || (currentStep === targetStep && currentSubstep >= targetSubstep);
}

function wordElementsForStep(step) {
  if (step <= 1) return "suffix -s/-es when applicable";
  if (step === 2) return "closed-syllable Latin bases and suffix -s/-es";
  if (step === 3) return "prefixes, Latin bases, suffix -ed/-ing";
  if (step === 4) return "prefixes, v-e Latin bases, suffix -ive";
  if (step === 5) return "open prefixes, Latin bases, taught suffixes";
  if (step === 6) return "prefixes, Latin bases, suffixes -able/-en/-er/-est/-ish/-or/-y/-ful/-less/-ly/-ment/-ness/-ty";
  if (step === 7) return "soft c/g spellings, ce/ge/dge, ph/tch, tion/sion, contractions, possessives, and cumulative prefixes/bases/suffixes";
  return "current word elements";
}

