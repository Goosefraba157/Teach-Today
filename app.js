function parseReaderPageSpec(text) {
  const inventory = {};
  text.trim().split("\n").forEach((line) => {
    const [id, reader, ...parts] = line.split("|");
    const pages = { wordlist: {}, sentences: {}, passage: {} };
    parts.forEach((part) => {
      const [key, value] = part.split(":");
      const type = key[0] === "w" ? "wordlist" : key[0] === "s" ? "sentences" : "passage";
      const level = key.slice(1);
      pages[type][level] = expandPageList(value);
    });
    inventory[id] = { reader: Number(reader), pages };
  });
  return inventory;
}

function expandPageList(value) {
  return value.split(",").flatMap((part) => {
    if (!part.includes("-")) return [Number(part)];
    const [start, end] = part.split("-").map(Number);
    return Array.from({ length: end - start + 1 }, (_, index) => start + index);
  });
}

