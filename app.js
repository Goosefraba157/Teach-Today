function sectionTwoReviewWords(skill, level = "AB", shuffleWords = false) {
  const prior = scopeMap.find((item) => item.id === priorSubstep(skill.id)) || skill;
  const realSource = readerWordsFromSubstep(prior.id, level);
  const nonsenseSource = readerNonsenseWordsForReview(prior.id, skill.id);
  const real = chooseWords(realSource, 4, shuffleWords);
  const nonsense = chooseWords(nonsenseSource, 2, shuffleWords);
  return real.concat(nonsense).slice(0, 6);
}

function readerWordsFromSubstep(substep, level = "AB") {
  const skill = scopeMap.find((item) => item.id === substep);
  if (!skill) return [];
  const pages = pageList(skill, "wordlist", level).slice().reverse();
  const resolved = resolvedLevel(skill, "wordlist", level);
  return uniqueWords(pages.flatMap((page) => cleanedReaderWords(
    window.readerWordlists?.[substep]?.[resolved]?.[String(page)]
    || window.readerWordlists?.[substep]?.AB?.[String(page)]
    || []
  )));
}

function readerNonsenseWordsForReview(preferredSubstep, currentSubstep) {
  const preferred = readerNonsenseWordsFromSubstep(preferredSubstep);
  if (preferred.length) return preferred;

  const current = readerNonsenseWordsFromSubstep(currentSubstep);
  if (current.length) return current;

  const currentIndex = scopeMap.findIndex((item) => item.id === currentSubstep);
  for (let index = currentIndex - 1; index >= 0; index -= 1) {
    const words = readerNonsenseWordsFromSubstep(scopeMap[index].id);
    if (words.length) return words;
  }
  for (let index = currentIndex + 1; index < scopeMap.length; index += 1) {
    const words = readerNonsenseWordsFromSubstep(scopeMap[index].id);
    if (words.length) return words;
  }
  return [];
}

function readerNonsenseWordsFromSubstep(substep) {
  const pages = window.readerWordlists?.[substep]?.N || {};
  return uniqueWords(Object.keys(pages)
    .sort((a, b) => Number(a) - Number(b))
    .flatMap((page) => cleanedReaderWords(pages[page])));
}

function uniqueWords(words) {
  return [...new Set(words.map((word) => String(word).trim()).filter(Boolean))];
}

function cleanedReaderWords(words) {
  let items = words.map((word) => String(word).trim()).filter(Boolean);
  const earlyDivisionIndex = items.slice(0, 4).findIndex((word) => word.toLowerCase() === "division");
  if (earlyDivisionIndex >= 0) {
    items = items.slice(earlyDivisionIndex + 1);
  }
  items = repairSplitReaderCompounds(items);
  const leadingLabels = new Set(["compound", "prefix", "suffix", "schwa", "mixed", "base", "word", "words", "end"]);
  while (items.length && leadingLabels.has(items[0].toLowerCase())) {
    items.shift();
  }
  return items.filter(isUsableReaderWord);
}

function repairSplitReaderCompounds(items) {
  const splitCompounds = new Map([
    ["mix up", "mix-up"],
    ["pop up", "pop-up"],
    ["sit up", "sit-up"],
    ["red hot", "red-hot"],
    ["run off", "run-off"],
    ["run on", "run-on"],
    ["shut off", "shut-off"],
    ["blast off", "blast-off"],
    ["lift off", "lift-off"]
  ]);
  const repaired = [];
  for (let index = 0; index < items.length; index += 1) {
    const pair = `${items[index].toLowerCase()} ${String(items[index + 1] || "").toLowerCase()}`;
    if (splitCompounds.has(pair)) {
      repaired.push(splitCompounds.get(pair));
      index += 1;
    } else {
      repaired.push(items[index]);
    }
  }
  return repaired;
}

function isUsableReaderWord(word) {
  const text = String(word || "").trim();
  if (!/^[a-z]+(?:-[a-z]+)?$/i.test(text)) return false;
  if (text.length < 2) return false;
  const readerLabels = new Set([
    "item", "isbn", "fourth", "edition", "published", "language", "training", "corporation",
    "webster", "road", "oxford", "united", "states", "america", "www", "prefix",
    "including", "nonsense", "multisyllabic", "division", "latin", "base", "word", "words",
    "reader", "student", "step", "page", "level", "compound", "end", "includes"
  ]);
  const soundCards = new Set(["sh", "ch", "th", "wh", "ck", "qu", "ng", "nk"]);
  const lower = text.toLowerCase();
  return !soundCards.has(lower) && !readerLabels.has(lower);
}

function sectionTwoCurrentWords(words, shuffleWords = false) {
  return chooseWords(words.filter(isUsableReaderWord), 8, shuffleWords);
}

function chooseWords(words, count, shuffleWords = false) {
  const source = uniqueWords(words);
  return (shuffleWords ? shuffled(source) : source).slice(0, count);
}

function shuffled(words) {
  const copy = words.slice();
  for (let index = copy.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(Math.random() * (index + 1));
    [copy[index], copy[swapIndex]] = [copy[swapIndex], copy[index]];
  }
  return copy;
}

