function saveLiveRecord(card, options = {}) {
  const group = activeGroup();
  const lesson = card._lesson;
  const skill = scopeMap.find((item) => item.id === lesson.substep);
  const student = group.activeStudent || group.students[0] || "";
  if (!student) return;
  if (typeof window.ttEnsureCurrentLessonSavedForData === "function") {
    window.ttEnsureCurrentLessonSavedForData();
  }
  stopLiveTimer(card);

  const chartHalf = activeChartHalf(card);
  const scoredCells = scoredChartCells(card);
  const allCells = [...card.querySelectorAll(".chart-cell[data-word]")];
  const total = scoredCells.length || 15;
  const correct = scoredCells.filter((cell) => cell.dataset.correct === "true").length;
  const wrongCount = Math.max(total - correct, 0);
  const seconds = Number(card.dataset.elapsed || 0);
  const accuracy = correct >= 12;
  const fluency = correct >= 14;
  const automaticity = accuracy && seconds > 0 && seconds <= 35;
  const wcpm = seconds ? Math.round((correct / seconds) * 60) : 0;
  const wordRecords = allCells.map((cell) => ({
    word: cell.dataset.word,
    section: cell.dataset.section,
    correct: cell.dataset.correct === "true",
    said: cell.querySelector(".said-input")?.value.trim() || ""
  }));
  const wrongWords = wordRecords.filter((item) => item.section === chartHalf && !item.correct).map((item) => item.word);
  const recommendation = recommendationFromScore(correct, seconds);
  const notes = card.querySelector(".live-notes").value.trim();
  const lessonMeta = typeof window.ttCurrentLessonRecordMeta === "function"
    ? window.ttCurrentLessonRecordMeta(lesson)
    : { lessonId: lesson.id || "" };

  const record = {
    id: `record-${Date.now()}`,
    date: new Date().toISOString(),
    displayDate: new Date().toLocaleDateString(),
    group: group.name,
    groupId: group.id,
    student,
    substep: lesson.substep,
    concept: skill?.title || lesson.title || lesson.focus || "",
    reader: lesson.reader,
    level: lesson.readerLevel,
    wordlistPage: lesson.wordlistPageNumber,
    chartHalf,
    correct,
    wrongCount,
    total,
    seconds,
    wcpm,
    accuracy,
    fluency,
    automaticity,
    wrongWords,
    wordRecords,
    notes,
    recommendation,
    ...lessonMeta
  };

  // Save audio recording if one was captured
  if (window._lastAudioBlob) {
    const blob = window._lastAudioBlob;
    const ext = blob.type.includes("ogg") ? "ogg" : "webm";
    const now = new Date();
    const dateStr = now.toISOString().slice(0, 10);
    const timeStr = now.toTimeString().slice(0, 8).replace(/:/g, "-");
    const lessonNum = (group.history?.length || 0) + 1;
    const safeName = (str) => String(str || "").replace(/[^a-zA-Z0-9_.-]/g, "_");
    const fileName = `${safeName(student)}_${safeName(lesson.substep)}_lesson${lessonNum}_${dateStr}_${timeStr}.${ext}`;
    record.audioRecordingId = record.id;
    record.audioFileName = fileName;
    saveAudioBlob(record.id, blob).catch((err) => console.warn("Audio save failed:", err));
    window._lastAudioBlob = null;
  }

  appState.masterRecords ||= [];
  appState.masterRecords.push(record);
  group.chartResults.push({
    date: record.displayDate,
    substep: record.substep,
    level: record.level,
    page: record.wordlistPage,
    chartHalf,
    correct,
    wrongCount,
    seconds,
    wcpm,
    accuracy,
    fluency,
    automaticity,
    labels: [accuracy && "accuracy", fluency && "fluency", automaticity && "automaticity"].filter(Boolean),
    decision: recommendation
  });
  saveState();
  card.dataset.lastSavedSignature = liveDataSignature(card);
  syncActiveStudentUi(group);
  setRecordingStatus(card, "Saved");
  card.querySelector(".live-score").textContent = `${options.automatic ? "Auto-saved" : "Saved"}: ${student} - ${titleCase(chartHalf)} half - ${correct}/${total} correct, ${wrongCount} wrong - ${recommendation}`;
}

function recommendationFromScore(correct, seconds) {
  if (correct < 12) return "Repeat same page next lesson";
  if (seconds && seconds <= 35 && correct >= 12) return "Advance page; automaticity met";
  if (correct >= 14) return "Advance page; keep brief fluency warm-up";
  return "Advance carefully; repeat as warm-up";
}

