function buildDictation(skill, dictationSet, trouble) {
  const words = dictationSet.words;
  const phrases = dictationSet.phrases;
  const sentences = dictationSet.sentences;
  const items = [
    `Sounds/parts: ${skill.target}`,
    `Dictation Book words: ${words.slice(0, 6).join(", ")}`,
    `Dictation Book phrases: ${phrases.length ? phrases.slice(0, 2).join("; ") : "source needed"}`,
    `Dictation Book sentence: ${sentences[0] || "source needed"}`
  ];

  if (trouble.has("suffix confusion")) {
    items.splice(1, 0, "Build: base word + suffix, then read the whole word.");
  }

  if (trouble.has("vowel sounds")) {
    items.splice(1, 0, "Quick contrast: student says vowel sound before writing.");
  }

  return items;
}

