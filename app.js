function recordMetricClass(record, type) {
  const correct = Number(record.correct || 0);
  const wrong = record.wrongCount ?? Math.max((record.total || 15) - correct, 0);
  const seconds = Number(record.seconds || 0);
  const wcpm = record.wcpm || wcpmForRecord(record);
  if (type === "correct") {
    if (correct >= 14) return "metric-good";
    if (correct >= 12) return "metric-watch";
    return "metric-risk";
  }
  if (type === "wrong") {
    if (wrong <= 1) return "metric-good";
    if (wrong <= 3) return "metric-watch";
    return "metric-risk";
  }
  if (type === "seconds") {
    if (seconds && seconds <= 35) return "metric-good";
    if (seconds && seconds <= 54) return "metric-watch";
    return "metric-risk";
  }
  if (type === "wcpm") {
    if (wcpm >= 26) return "metric-good";
    if (wcpm >= 17) return "metric-watch";
    return "metric-risk";
  }
  return "";
}

