function updateLiveScore(card) {
  const cells = scoredChartCells(card);
  const total = cells.length || 15;
  const correct = cells.filter((cell) => cell.dataset.correct === "true").length;
  const wrong = Math.max(total - correct, 0);
  const seconds = Number(card.dataset.elapsed || 0);
  const accuracy = correct >= 12;
  const fluency = correct >= 14;
  const automaticity = accuracy && seconds > 0 && seconds <= 35;
  const labels = [];
  if (accuracy) labels.push("accuracy");
  if (fluency) labels.push("fluency");
  if (automaticity) labels.push("automaticity");
  const halfLabel = titleCase(activeChartHalf(card));
  card.querySelector(".live-score").textContent = `${halfLabel} half: ${correct}/${total} correct, ${wrong} wrong${seconds ? ` in ${seconds} sec` : ""} - ${labels.join(", ") || "repeat"}`;
}

