function wordsForChartingPage(skill, assignment) {
  const cleaned = chartingWordsForReaderPage(skill.id, assignment.level, assignment.page);
  if (cleaned.length >= 15) return cleaned;

  const pages = pageList(skill, "wordlist", assignment.level);
  const resolved = resolvedLevel(skill, "wordlist", assignment.level);
  const startIndex = Math.max(pages.indexOf(assignment.page), 0);
  for (let index = startIndex + 1; index < pages.length; index += 1) {
    const nextData = window.readerWordlists?.[skill.id]?.[resolved]?.[String(pages[index])]
      || window.readerWordlists?.[skill.id]?.AB?.[String(pages[index])]
      || [];
    const cleanedNext = extractChartingWords(nextData);
    if (cleanedNext.length >= 15) return cleanedNext;
  }

  if (cleaned.length) return cleaned;
  return skill.realWords.concat(skill.nonsenseWords);
}

function chartingWordsForReaderPage(substep, level, page) {
  const indexed = chartingPageEntry(substep, level, page);
  if (indexed.count) return indexed.words;
  const raw = window.readerWordlists?.[substep]?.[level]?.[String(page)]
    || window.readerWordlists?.[substep]?.AB?.[String(page)]
    || [];
  return extractChartingWords(raw);
}

function chartingPageEntry(substep, level, page) {
  const entry = window.readerChartIndex?.[substep]?.[level]?.[String(page)]
    || window.readerChartIndex?.[substep]?.AB?.[String(page)];
  if (!entry) return { top: [], bottom: [], words: [], count: 0, status: "missing" };
  const top = entry.t || entry.top || [];
  const bottom = entry.b || entry.bottom || [];
  const count = Number(entry.c ?? entry.count ?? top.length + bottom.length);
  return {
    top,
    bottom,
    words: top.concat(bottom),
    count,
    status: entry.s || entry.status || (count >= 30 ? "full" : count >= 15 ? "partial" : "empty")
  };
}

function extractChartingWords(words) {
  let items = repairSplitReaderCompounds(words.map((word) => String(word).trim().toLowerCase()).filter(Boolean));
  if (items.some((word) => ["isbn", "published", "corporation", "webster"].includes(word))) return [];
  const leadingLabels = new Set([
    "a", "b", "c", "g", "j", "s", "page", "pages", "ar", "er", "ir", "or", "ur", "ai", "ay", "ee", "ea", "ey",
    "oi", "oy", "oa", "oe", "ow", "ou", "oo", "ue", "ew", "au", "aw", "eu", "ui",
    "ph", "tch", "dge", "nce", "nge", "lge", "tion", "sion", "ion",
    "hard", "soft", "mixed", "compound", "contractions", "possessive", "nouns", "singular",
    "plural", "prefix", "suffix", "bases", "base", "all", "taught", "elements", "another", "stand", "alone",
    "schwa", "affixes", "multiple", "intact", "includes"
  ]);
  while (items.length && leadingLabels.has(items[0])) items.shift();
  return items.filter((word) => isChartingReaderWord(word));
}

function isChartingReaderWord(word) {
  const text = String(word || "").trim();
  if (!/^[a-z]+(?:-[a-z]+)?$/i.test(text)) return false;
  if (text.length < 2) return false;
  const frontMatter = new Set([
    "item", "isbn", "fourth", "edition", "published", "language", "training", "corporation",
    "webster", "road", "oxford", "united", "states", "america", "www", "reader", "student", "step", "level", "page", "pages"
  ]);
  return !frontMatter.has(text.toLowerCase());
}

function sentenceDataForPage(skill, assignment) {
  const indexed = sentencePageEntry(skill.id, assignment.level, assignment.page);
  if (indexed) return indexed;
  return window.readerSentences?.[skill.id]?.[assignment.level]?.[String(assignment.page)]
    || window.readerSentences?.[skill.id]?.AB?.[String(assignment.page)]
    || { highFrequency: [], sentences: [] };
}

function dictationSelection(substep, level, pageWords) {
  const bank = dictationValues("words", substep, level);
  const compatible = pageWords.filter((word) => bank.includes(word));
  const words = compatible.length >= 4 ? compatible : bank.slice(0, 12);
  return {
    words: words.length ? words : pageWords,
    phrases: dictationItems("phrases", substep, level, 3),
    sentences: dictationItems("sentences", substep, level, 2)
  };
}

function dictationItems(type, substep, level, count) {
  const items = dictationValues(type, substep, level);
  return items.slice(0, count);
}

function sentencePageEntry(substep, level, page) {
  const entry = window.readerSentenceIndex?.[substep]?.[level]?.[String(page)]
    || window.readerSentenceIndex?.[substep]?.AB?.[String(page)];
  if (!entry) return null;
  return {
    highFrequency: entry.h || entry.highFrequency || [],
    sentences: entry.s || entry.sentences || []
  };
}

function dictationValues(type, substep, level = "AB") {
  if (type === "phrases") {
    const phraseRows = structuredDictationPhraseRows(substep);
    if (phraseRows.length) return phraseRows.flatMap((row) => row.phrases || []);
  }
  if (type === "sentences") {
    const sentenceGroups = structuredDictationSentenceGroups(substep, level);
    if (sentenceGroups.length) return flattenDictationSentenceGroups(sentenceGroups);
  }
  const key = type === "highFrequency" ? "hfw" : type;
  const indexed = window.dictationIndex?.[substep]?.[level]?.[key]
    || window.dictationIndex?.[substep]?.AB?.[key]
    || window.dictationIndex?.[substep]?.A?.[key]
    || window.dictationIndex?.[substep]?.B?.[key]
    || window.dictationIndex?.[substep]?.N?.[key];
  if (indexed?.length) return indexed;
  if (type === "highFrequency") return window.dictationContent?.highFrequency?.[substep] || [];
  return window.dictationContent?.[type]?.[substep]?.[level]
    || window.dictationContent?.[type]?.[substep]?.AB
    || [];
}

function structuredDictationPhraseRows(substep) {
  return window.dictationPhraseIndex?.[substep] || [];
}

function structuredDictationSentenceGroups(substep, level = "AB") {
  const stepIndex = window.dictationSentenceIndex?.[substep] || {};
  const resolved = level === "B" ? "B" : "AB";
  const groups = stepIndex[resolved]?.groups || [];
  if (groups.length) return groups;
  return stepIndex.AB?.groups || [];
}

function flattenDictationSentenceGroups(groups, kind = null) {
  return groups
    .filter((group) => !kind || group.kind === kind)
    .flatMap((group) => group.chunks || [])
    .flatMap((chunk) => chunk.sentences || []);
}

function reviewWordsForLesson(group, skill, assignment) {
  const repeatPage = group.warmupRepeat;
  const sourcePage = repeatPage || (group.trouble.length ? previousPageForAssignment(skill, assignment) : null);
  const words = sourcePage ? chartingWordsForReaderPage(skill.id, assignment.level, sourcePage) : [];
  if (words.length) return words.slice(0, 8);

  const prior = priorSubstep(skill.id);
  const reviewBank = dictationValues("words", prior, assignment.level);
  if (reviewBank.length) return reviewBank.slice(0, 8);

  const currentBank = dictationValues("words", skill.id, assignment.level);
  return currentBank.slice(0, 6);
}

function priorSubstep(substep) {
  const index = scopeMap.findIndex((item) => item.id === substep);
  return index > 0 ? scopeMap[index - 1].id : substep;
}

function previousPageForAssignment(skill, assignment) {
  const pages = pageList(skill, "wordlist", assignment.level);
  const index = pages.indexOf(assignment.page);
  return index > 0 ? pages[index - 1] : null;
}

