function hasUnsavedLiveData(card) {
  const meaningful = Number(card.dataset.elapsed || 0) > 0
    || Boolean(card.querySelector(".live-notes")?.value.trim())
    || scoredChartCells(card).some((cell) => {
      const said = cell.querySelector(".said-input")?.value.trim();
      return cell.dataset.correct === "false" || Boolean(said);
    });
  if (!meaningful) return false;
  return liveDataSignature(card) !== card.dataset.lastSavedSignature;
}

function liveDataSignature(card) {
  const group = activeGroup();
  const parts = [
    group.activeStudent || "",
    card.dataset.lessonId || "",
    activeChartHalf(card),
    card.dataset.elapsed || "0",
    card.querySelector(".live-notes")?.value.trim() || ""
  ];
  scoredChartCells(card).forEach((cell) => {
    parts.push([
      cell.dataset.word,
      cell.dataset.correct,
      cell.querySelector(".said-input")?.value.trim() || ""
    ].join(":"));
  });
  return parts.join("|");
}

