function lessonFocus(index, total, trouble) {
  const finalDay = index === total - 1;
  if (finalDay) return { title: "Cumulative check and transfer", label: "mastery" };
  if (index === 0) return { title: "Introduce and read", label: "accuracy" };
  if (trouble.has("dictation") && index === 2) return { title: "Spelling and dictation lift", label: "dictation" };
  if (trouble.has("slow decoding") && index >= 1) return { title: "Repeated reading for automaticity", label: "fluency" };
  if (trouble.has("suffix confusion")) return { title: "Word building and meaning", label: "word parts" };
  return { title: index % 2 ? "Controlled practice" : "Application and transfer", label: "practice" };
}

