const assert = require('node:assert/strict');
const fs = require('node:fs');
const rf = require('../reading-fluency.js');
const sync = require('../sync-safety.js');
const words = rf.tokens("THE TITLE\nI couldn't read—at first. A well-known cat.");
assert.deepEqual(words,['THE','TITLE','I',"couldn't",'read—','at','first.','A','well-known','cat.']);
assert.deepEqual(rf.score(words,7,[1,1,2,9,-1,1.5],60),{attempted:8,errors:2,correct:6,wcpm:6,accuracy:75});
assert.deepEqual(rf.score(words,-1,[0],60),{attempted:0,errors:0,correct:0,wcpm:0,accuracy:null});
assert.equal(rf.score(words,9,[],30).wcpm,20);
for(const last of [null,10,-2,1.5])assert.throws(()=>rf.score(words,last,[],60));
for(const secs of [0,-1,61,NaN,Infinity])assert.throws(()=>rf.score(words,2,[],secs));
const passages=[{id:'a',grade:1},{id:'b',grade:1},{id:'c',grade:2}];
assert.deepEqual(rf.unused(passages,[{studentId:'s1',passageId:'a'}],[{studentId:'s2',passageId:'b'}],'s1',1),[{id:'b',grade:1}]);
assert.equal(rf.unused(passages,[],[{studentId:'s1',passageId:'a'},{studentId:'s1',passageId:'b'}],'s1',1).length,0);
const clean=rf.payload({title:'A title',text:'A passage',studentId:'PRIVATE',errors:[1],wcpm:90,notes:'PRIVATE',timer:60});
assert.deepEqual(Object.keys(clean).sort(),['displayMode','groupName','mode','passageText','passageTitle','sectionLabel','sourceSection'].sort());
assert(!JSON.stringify(clean).includes('PRIVATE'));
assert.equal(rf.payload(null).mode,'private');
const form={id:'star-por-en-g4-f02',grade:4,form:2,title:'A title',text:'A passage long enough to be checked carefully before scoring.',sourceImage:'data:image/jpeg;base64,YWJj',sourcePage:3,verified:true};
const library={format:'teach-today-fluency-library-v1',passages:[form]};
assert.equal(rf.validateLibrary(library)[0].verified,false);
assert.equal(rf.validateLibrary(library)[0].sourcePage,3);
assert.throws(()=>rf.validateLibrary({...library,passages:[form,form]}));
assert.throws(()=>rf.validateLibrary({...library,passages:[{...form,sourceImage:'javascript:alert(1)'}]}));
assert.throws(()=>rf.validateLibrary({...library,passages:[{...form,id:'star-por-en-g5-f02'}]}));
const base={appState:{readingFluencyRecords:[],readingFluencyAssignments:[]}};
const local={appState:{readingFluencyRecords:[{id:'l',wcpm:10}],readingFluencyAssignments:[{id:'al'}]}};
const remote={appState:{readingFluencyRecords:[{id:'r',wcpm:20}],readingFluencyAssignments:[{id:'ar'}]}};
const merged=sync.mergePayloads(base,local,remote);
assert.deepEqual(new Set(merged.appState.readingFluencyRecords.map(r=>r.id)),new Set(['l','r']));
assert.deepEqual(new Set(merged.appState.readingFluencyAssignments.map(r=>r.id)),new Set(['al','ar']));
const worker=fs.readFileSync(require('node:path').join(__dirname,'../service-worker.js'),'utf8');
assert(worker.includes('./reading-fluency.js?v=20261103-fluency-1'));
assert(!worker.includes('star-cbm-english-library.json'));
console.log('Reading fluency scoring, identity, library privacy, and additive sync checks passed.');
